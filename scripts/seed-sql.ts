// Writes the demo data as a SQL file, for loading into the Cloudflare (remote) database:
//
//   npm run db:seed:remote
//
// The local database is seeded through the repository instead (npm run db:seed). The remote one
// can't be reached from a plain Node script, but `wrangler d1 execute --remote --file` can run SQL.
// Phase 4's daily reset will reseed it automatically.

import { mkdirSync, writeFileSync } from "node:fs";
import { buildSeedData } from "../worker/data/seed.ts";
import { riyadhToday } from "../worker/domain/dates.ts";

const OUTPUT = ".wrangler/seed.sql";

function sqlValue(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  // Single quotes are escaped by doubling them, the SQL way.
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** referenceCode -> reference_code: the TypeScript field names map one-to-one onto the columns. */
function toColumn(field: string): string {
  return field.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
}

function insert(table: string, row: object): string {
  const entries = Object.entries(row);
  const columns = entries.map(([field]) => toColumn(field)).join(", ");
  const values = entries.map(([, value]) => sqlValue(value)).join(", ");
  return `INSERT INTO ${table} (${columns}) VALUES (${values});`;
}

const now = new Date();
const today = riyadhToday(now);
const seed = buildSeedData(today, now.toISOString());

const statements = [
  // Same order as D1Repository.replaceAllData: children before the rooms they point to.
  "DELETE FROM conversations;",
  "DELETE FROM tickets;",
  "DELETE FROM bookings;",
  "DELETE FROM rooms;",
  ...seed.rooms.map((room) => insert("rooms", room)),
  ...seed.bookings.map((booking) => insert("bookings", booking)),
  ...seed.tickets.map((ticket) => insert("tickets", ticket)),
];

mkdirSync(".wrangler", { recursive: true });
writeFileSync(OUTPUT, `-- Demo data for ${today} (Riyadh). Generated by scripts/seed-sql.ts.\n${statements.join("\n")}\n`);
console.log(`Wrote ${statements.length} statements to ${OUTPUT}`);
